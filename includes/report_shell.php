<?php
declare(strict_types=1);

/** Render the standard printable report header (opens <html>…<main>). */
function reportHeader(string $title, string $subtitle = '', array $meta = []): void {
    $inst = setting('institution_name', 'Institution');
    $sys  = setting('system_title', 'APTARS');
    ?>
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title><?= e($title) ?> &middot; <?= e($sys) ?></title>
<link href="<?= e(asset('assets/vendor/bootstrap/bootstrap.min.css')) ?>" rel="stylesheet">
<link href="<?= e(asset('assets/vendor/bootstrap-icons/bootstrap-icons.min.css')) ?>" rel="stylesheet">
<link href="<?= e(asset('assets/css/style.css')) ?>" rel="stylesheet">
<link href="<?= e(asset('assets/css/print.css')) ?>" rel="stylesheet">
</head>
<body class="report-body">

<div class="report-toolbar no-print">
  <a href="javascript:history.back()" class="btn btn-sm btn-outline-secondary"><i class="bi bi-arrow-left"></i> Back</a>
  <a href="<?= e(baseUrl('reports/index.php')) ?>" class="btn btn-sm btn-outline-secondary"><i class="bi bi-list-ul"></i> All Reports</a>
  <div class="ms-auto">
    <button type="button" class="btn btn-sm btn-primary" onclick="window.print()"><i class="bi bi-printer"></i> Print / Save as PDF</button>
  </div>
</div>

<main class="report-page">
  <header class="report-header">
    <div class="report-institution"><?= e($inst) ?></div>
    <h1 class="report-title"><?= e($title) ?></h1>
    <?php if ($subtitle !== ''): ?><p class="report-subtitle"><?= e($subtitle) ?></p><?php endif; ?>
    <?php if ($meta): ?>
      <div class="report-meta">
        <?php foreach ($meta as $k => $v): ?>
          <span><strong><?= e($k) ?>:</strong> <?= e((string)$v) ?></span>
        <?php endforeach; ?>
      </div>
    <?php endif; ?>
  </header>
    <?php
}

/** Close the report (footer, signature block, scripts). */
function reportFooter(string $preparedBy = ''): void {
    $now = date('d M Y, H:i');
    ?>
  <footer class="report-footer">
    <div class="report-signatures">
      <div class="signature-block"><div class="signature-line"></div><span>Prepared by<?= $preparedBy !== '' ? ' (' . e($preparedBy) . ')' : '' ?></span></div>
      <div class="signature-block"><div class="signature-line"></div><span>Head of Department</span></div>
      <div class="signature-block"><div class="signature-line"></div><span>Registrar / Dean</span></div>
    </div>
    <div class="report-meta-foot">
      <span>Generated by <?= e(setting('system_title','APTARS')) ?> on <?= e($now) ?></span>
    </div>
  </footer>
</main>
</body>
</html>
    <?php
}

/** Inline loading of a Chart.js chart for print. */
function chartCanvas(string $id, int $height = 200): string {
    return '<canvas id="' . e($id) . '" height="' . (int)$height . '"></canvas>';
}